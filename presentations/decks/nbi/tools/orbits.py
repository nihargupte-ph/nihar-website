"""Cartoon for page-12 (degeneracy & waveform length): two equal-mass black holes on an eccentric orbit
with spins along the orbital axis, beside two on a circular orbit with spins tilted off it (precessing).
A still image: an animated version was too distracting next to the figure.

Run from the deck folder:  python tools/orbits.py  ->  static/nametune/orbits.svg

Each binary is drawn at one moment of its orbit (Kepler's equation, sampled in equal steps of time;
SNAP picks the step), the eccentric one partway out from pericentre. The orbital plane is
drawn tilted towards the viewer: screen y = 0.38 * (in-plane y) - 0.92 * (height above the plane).
"""
from pathlib import Path

import numpy as np

OUT = Path(__file__).resolve().parents[1] / 'static' / 'nametune' / 'orbits.svg'
N = 72                       # samples per orbit
SNAP = {'ecc': 14, 'circ': 9}  # which sample each binary is drawn at
SY, SZ = 0.42, 0.91          # projection of the in-plane y and of the orbital axis
BLUE, ORANGE, INK = '#4169e1', '#ff8c00', '#504c44'
R_BALL, L_SPIN = 9, 32


def eccentric(a=66.0, e=0.6):
    M = 2 * np.pi * np.arange(N + 1) / N
    E = M.copy()
    for _ in range(50):
        E = E - (E - e * np.sin(E) - M) / (1 - e * np.cos(E))
    x, y = a * (np.cos(E) - e), a * np.sqrt(1 - e ** 2) * np.sin(E)
    return np.c_[x, SY * y]


def circular(r=50.0):
    t = 2 * np.pi * np.arange(N + 1) / N
    return np.c_[r * np.cos(t), SY * r * np.sin(t)]


def orbit_path(xy):
    return 'M' + 'L'.join(f'{x:.1f} {y:.1f}' for x, y in xy) + 'Z'


def ball(x, y, spin, colour):
    """One black hole: a shaded sphere and its spin arrow (screen-space offset of the arrow tip)."""
    return (f'<g transform="translate({x:.1f} {y:.1f})"><circle r="{R_BALL}" fill="url(#bh)"/>'
            f'<line x1="0" y1="0" x2="{spin[0]:.1f}" y2="{spin[1]:.1f}" class="spin" stroke="{colour}" '
            f'marker-end="url(#head-{colour[1:]})"/></g>')


def precessing_spin(theta=np.radians(40), phase=0.0):
    psi = phase + 2 * np.pi * np.arange(N + 1) / N
    sx, sy, sz = np.sin(theta) * np.cos(psi), np.sin(theta) * np.sin(psi), np.cos(theta)
    return np.c_[L_SPIN * sx, L_SPIN * (SY * sy - SZ * sz)]


def main():
    W, H = 560, 150
    ecc, circ = eccentric(), circular()
    ex, ey, cx, cy = 150, 66, 430, 66
    e1, c1, up = ecc[SNAP['ecc']], circ[SNAP['circ']], (0.0, -SZ * L_SPIN)
    body = [
        f'<path d="{orbit_path([(ex + x, ey + y) for x, y in ecc])}" class="orbit"/>',
        f'<path d="{orbit_path([(ex - x, ey - y) for x, y in ecc])}" class="orbit"/>',
        f'<path d="{orbit_path([(cx + x, cy + y) for x, y in circ])}" class="orbit"/>',
        f'<line x1="{ex}" y1="{ey + 4}" x2="{ex}" y2="{ey - 58}" class="axis"/>',
        f'<line x1="{cx}" y1="{cy + 4}" x2="{cx}" y2="{cy - 58}" class="axis"/>',
        ball(ex + e1[0], ey + e1[1], up, BLUE), ball(ex - e1[0], ey - e1[1], up, BLUE),
        ball(cx + c1[0], cy + c1[1], precessing_spin()[0], ORANGE),
        ball(cx - c1[0], cy - c1[1], precessing_spin(phase=2.3)[0], ORANGE),
        f'<text x="{ex}" y="{H - 6}" fill="{BLUE}">eccentric, aligned spins</text>',
        f'<text x="{W / 2}" y="{ey + 6}" fill="{INK}" class="vs">vs</text>',
        f'<text x="{cx}" y="{H - 6}" fill="{ORANGE}">circular, precessing spins</text>',
    ]
    heads = ''.join(f'<marker id="head-{c[1:]}" viewBox="0 0 10 10" refX="6" refY="5" markerWidth="4" markerHeight="4" '
                    f'orient="auto-start-reverse"><path d="M0 0L10 5L0 10z" fill="{c}"/></marker>' for c in (BLUE, ORANGE))
    svg = (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {W} {H}">'
           '<!-- generated by tools/orbits.py -->'
           f'<defs><radialGradient id="bh" cx="35%" cy="32%" r="70%"><stop offset="0" stop-color="#6b6b6b"/>'
           f'<stop offset=".45" stop-color="#1a1a1a"/><stop offset="1" stop-color="#000"/></radialGradient>{heads}</defs>'
           f'<style>.orbit{{fill:none;stroke:{INK};stroke-opacity:.4;stroke-width:1.2;stroke-dasharray:3 3}}'
           f'.axis{{stroke:{INK};stroke-opacity:.35;stroke-width:1}}'
           '.spin{stroke-width:3;stroke-linecap:round}'
           'text{font:500 17px Inter,system-ui,sans-serif;text-anchor:middle}.vs{font-size:17px;opacity:.6;font-style:italic}</style>'
           + ''.join(body) + '</svg>\n')
    OUT.write_text(svg)
    print(f'wrote {OUT.relative_to(Path.cwd()) if OUT.is_relative_to(Path.cwd()) else OUT}')


if __name__ == '__main__':
    main()
